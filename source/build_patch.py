"""Build same-size, menu-only IFR edits for the supplied GZ302EA .314 image."""
from pathlib import Path
import hashlib
import json
import struct
import uuid

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent
GUID = uuid.UUID('E39AC631-48ED-445E-9042-55B34F405844').bytes_le
TARGETS = {3: 'CPU menu', 4: 'iGPU menu', 6: 'PBO menu',
           14: 'CPU frequency field', 15: 'CPU voltage field',
           108: 'iGPU Curve Optimizer entry', 109: 'CPU Curve Optimizer entry'}


def opcodes(b, start, end):
    p = start
    stack = []
    while p < end:
        op, size = b[p], b[p + 1] & 127
        assert size >= 2 and p + size <= end, ('invalid opcode', p)
        yield p, op, size, tuple(stack)
        if op == 0x29:
            assert stack, ('unbalanced end', p)
            stack.pop()
        if b[p + 1] & 128:
            stack.append((p, op))
        p += size
    assert p == end and not stack


def false_expression(length):
    # A scoped constant followed by unary NOTs, then END; final value is FALSE.
    assert length >= 4 and length % 2 == 0
    count = (length - 4) // 2
    return bytes([0x46 if count % 2 else 0x47, 0x82]) + bytes([0x17, 2]) * count + bytes([0x29, 2])


def main():
    original = (ROOT / 'AodDxe.bin').read_bytes()
    candidates = []
    for i in range(len(original) - 26):
        n = int.from_bytes(original[i:i + 3], 'little')
        if original[i + 3] == 2 and original[i + 4] == 14 and original[i + 6:i + 22] == GUID and i + n <= len(original):
            candidates.append((i, n))
    assert len(candidates) == 1
    off, size = candidates[0]
    patched = bytearray(original)
    records = []
    for p, op, length, stack in opcodes(original, off + 4, off + size):
        if op not in (5, 6, 7, 15) or length < 13:
            continue
        question = struct.unpack_from('<H', original, p + 6)[0]
        if question not in TARGETS:
            continue
        scope, sop = stack[-1]
        assert sop == 10
        anchor_length = length if op == 15 else 13
        before = original[scope:p + anchor_length]
        after = bytearray(before)
        if question in (108, 109):
            # Turn only the capability comparison into TRUE. Keep the existing
            # PBO==Advanced dependency, NOT/OR operators and entire scope intact.
            marker = bytes.fromhex('12 06 b4 00 01 00')
            scoped_marker = bytes.fromhex('12 86 b4 00 01 00')
            needle = scoped_marker if scoped_marker in before else marker
            at = before.index(needle)
            after[at:at + 6] = bytes([0x46, 0x82 if needle[1] & 128 else 2, 0x46, 2, 0x15, 2])
            purpose = 'Expose capability-gated entry; preserve PBO Advanced dependency'
        else:
            after[2:p - scope] = false_expression(p - scope - 2)
            purpose = 'Make this menu/field suppression expression FALSE'
        assert len(before) == len(after)
        patched[scope:p + anchor_length] = after
        records.append({'question_id': question, 'label': TARGETS[question],
                        'module_offset': scope, 'forms_offset': scope - off,
                        'original': before.hex(), 'replacement': after.hex(), 'purpose': purpose})
    assert len(records) == len(TARGETS)
    list(opcodes(patched, off + 4, off + size))
    OUT.mkdir(exist_ok=True)
    (OUT / 'AodDxe.MENU_ONLY_NOT_FLASH_IMAGE.bin').write_bytes(patched)
    (OUT / 'Aod.forms.menu-unlocked.bin').write_bytes(patched[off:off + size])
    manifest = {'input_sha256': hashlib.sha256(original).hexdigest(),
                'output_sha256': hashlib.sha256(patched).hexdigest(),
                'forms_offset': off, 'forms_size': size,
                'changed_bytes': sum(a != b for a, b in zip(original, patched)),
                'edits': records,
                'limits': ['Menu-only patch; not a flashable BIOS',
                           'No SMU capability bits, executable code, default values or numeric ranges changed',
                           'Hardware voltage support and boot-time use remain unverified']}
    (OUT / 'patch-manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    header = ['/* Generated by build_patch.py; exact GZ302EA .314 IFR anchors. */',
              'typedef struct { const unsigned char *old_data, *new_data; unsigned int size; } PATCH;']
    for i, record in enumerate(records):
        for field, tag in [('original', 'old'), ('replacement', 'new')]:
            values = ','.join('0x' + record[field][j:j+2] for j in range(0, len(record[field]), 2))
            header.append(f'static const unsigned char patch_{i}_{tag}[] = {{{values}}};')
    header.append('static const PATCH patches[] = {')
    for i in range(len(records)):
        header.append(f'{{patch_{i}_old,patch_{i}_new,sizeof(patch_{i}_old)}},')
    header.append('};')
    (OUT / 'patches.h').write_text('\n'.join(header) + '\n', encoding='ascii')
    print(json.dumps({k: v for k, v in manifest.items() if k != 'edits'}, indent=2))


if __name__ == '__main__':
    main()
